#!/usr/bin/env python3
"""Rebuild assets/verified-quotes.json: SHA-256 hashes of every testimonial quote that the
clone renders verbatim from a string literal (i.e. real customer/partner/employee copy),
paired with the person it is attributed to.

Why hashes: a PageSpec slide with source "verified" must reproduce one of these quotes
exactly and attribute it to the same person (semantic rule QUOTE_PROVENANCE). Storing
hashes, not text, keeps this repo from becoming a second copy of third-party quotes.
Quotes the clone renders as length-matched placeholders (filler()/ph() calls) are not
literals and are therefore never registered.

Run: python3 extraction/build_verified_quotes.py [--check]
Without the sibling src/ tree (a standalone copy) it prints a notice and exits 0.
"""
import hashlib
import json
import os
import re
import sys

DR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROJECT = os.path.dirname(DR)
SRC = os.path.join(PROJECT, "src")
OUT = os.path.join(DR, "assets", "verified-quotes.json")

# quote: '...'  /  quote: "..."  /  quote:\n  "..."   (single-line JS string literals)
QUOTE_RE = re.compile(r"""quote:\s*(?P<q>['"])(?P<text>(?:\\.|(?!(?P=q)).)*)(?P=q)""", re.S)
NAME_RE = re.compile(r"""name:\s*(['"])((?:\\.|(?!\1).)*)\1""")
CURLY_RE = re.compile(r"“([^”]{20,})”")


def norm(s):
    s = s.replace("\\'", "'").replace('\\"', '"').replace("\\\\", "\\")
    return re.sub(r"\s+", " ", s).strip()


def digest(text):
    return hashlib.sha256(norm(text).encode("utf-8")).hexdigest()


def collect():
    entries = []
    for root, _, files in os.walk(SRC):
        for fn in sorted(files):
            if not fn.endswith((".js", ".jsx")) or fn in ("filler.js", "placeholder.js"):
                continue
            p = os.path.join(root, fn)
            rel = os.path.relpath(p, PROJECT)
            txt = open(p, encoding="utf-8").read()
            for m in QUOTE_RE.finditer(txt):
                if norm(m.group("text")).lower().startswith("placeholder") or len(norm(m.group("text"))) < 20:
                    continue
                before = txt[max(0, m.start() - 600):m.start()]
                after = txt[m.end():m.end() + 300]
                names = NAME_RE.findall(before)
                person = norm(names[-1][1]) if names else None
                if person is None:
                    na = NAME_RE.findall(after)
                    person = norm(na[0][1]) if na else None
                line = txt[:m.start()].count("\n") + 1
                entries.append({"sha256": digest(m.group("text")), "person": person, "file": rel, "line": line})
            if fn == "InsightsPage.jsx":
                for m in CURLY_RE.finditer(txt):
                    line = txt[:m.start()].count("\n") + 1
                    entries.append({"sha256": digest(m.group(1)), "person": "Upwork", "file": rel, "line": line})
    seen, out = set(), []
    for e in sorted(entries, key=lambda e: (e["file"], e["line"])):
        k = (e["sha256"], e["person"])
        if k not in seen:
            seen.add(k)
            out.append(e)
    return out


def build():
    return {
        "$comment": "GENERATED by extraction/build_verified_quotes.py from string literals in the clone's src/. Normalisation: JS escapes unescaped, whitespace collapsed, trimmed; then SHA-256 (hex).",
        "normalisation": "unescape \\' \\\" \\\\; collapse whitespace; strip; utf-8; sha256 hex",
        "quotes": collect(),
    }


if __name__ == "__main__":
    if not os.path.isdir(SRC):
        print("src/ not present beside design-repo/: verified-quote registry not rebuilt (standalone copy)")
        sys.exit(0)
    text = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("verified quotes up to date" if ok else "verified quotes OUT OF DATE")
        sys.exit(0 if ok else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(text)
    print("wrote assets/verified-quotes.json")
