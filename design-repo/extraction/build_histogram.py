#!/usr/bin/env python3
"""Rebuild extraction/style-histogram.json from the sibling recon/ capture dumps.

The histogram is the usage-count evidence behind tokens/00-foundation/*. It is computed
from the Playwright computed-style dumps the recon pass saved (42 route x width files:
company/, content/out/, conversion/). Third-party UI (the CookieYes banner, UA
"sans-serif" text, the skip link) is excluded so only Siena's own styles are counted.

Run: python3 extraction/build_histogram.py [--check]
Without the sibling recon/ tree (a standalone copy) it prints a notice and exits 0.
"""
import collections
import glob
import json
import os
import re
import sys

DR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROJECT = os.path.dirname(DR)
RECON = os.path.join(PROJECT, "recon")
OUT = os.path.join(DR, "extraction", "style-histogram.json")

FONT_RE = re.compile(r"^(?P<ff>.+?) (?P<fw>\d{3}) (?P<fs>[\d.]+px)/(?P<lh>[^ ]+)")


def norm_color(c):
    c = (c or "").strip()
    m = re.fullmatch(r"rgba?\(([^)]*)\)", c)
    if not m:
        return None
    parts = [p.strip() for p in m.group(1).split(",")]
    r, g, b = (int(float(x)) for x in parts[:3])
    a = float(parts[3]) if len(parts) > 3 else 1.0
    if a == 0:
        return None
    if a == 1:
        return "#%02X%02X%02X" % (r, g, b)
    return "rgba(%d,%d,%d,%g)" % (r, g, b, a)


def skip_family(ff):
    ff = (ff or "").strip().strip('"')
    return ff in ("", "sans-serif", "serif", "Times New Roman", "Arial") or ff.startswith("-apple")


def collect():
    h = {k: collections.Counter() for k in ("textColor", "background", "fontFamily", "fontSize", "fontWeight", "radius")}
    sources = []
    for f in sorted(glob.glob(os.path.join(RECON, "**", "*.json"), recursive=True)):
        rel = os.path.relpath(f, PROJECT)
        try:
            d = json.load(open(f))
        except Exception:  # noqa: BLE001
            continue
        if not isinstance(d, dict):
            continue
        texts, boxes = [], []
        if isinstance(d.get("data"), dict) and isinstance(d["data"].get("out"), list):
            for n in d["data"]["out"]:
                s = n.get("s", {})
                m = FONT_RE.match(s.get("font", ""))
                if m:
                    texts.append({"ff": m["ff"], "fw": m["fw"], "fs": m["fs"], "c": s.get("color")})
                if s.get("bg") or s.get("rad"):
                    boxes.append({"bg": s.get("bg"), "rad": s.get("rad")})
        elif isinstance(d.get("texts"), list):
            texts = d["texts"]
            boxes = [{"bg": b.get("bg"), "rad": b.get("rad") or b.get("br")} for b in d.get("boxes", [])]
        else:
            continue
        sources.append(rel)
        for t in texts:
            ff = (t.get("ff") or "").split(",")[0].strip().strip('"')
            if skip_family(ff) or (t.get("t") or "").startswith("Skip to main"):
                continue
            h["fontFamily"][ff] += 1
            if t.get("fs"):
                h["fontSize"][t["fs"]] += 1
            if t.get("fw"):
                h["fontWeight"][str(t["fw"])] += 1
            c = norm_color(t.get("c"))
            if c:
                h["textColor"][c] += 1
        for b in boxes:
            c = norm_color(b.get("bg"))
            if c:
                h["background"][c] += 1
            r = (b.get("rad") or "").split("|")[0].split(" ")[0]
            if r and r not in ("0px", "0"):
                h["radius"][r] += 1
    return h, sources


def build():
    h, sources = collect()
    top = {k: dict(v.most_common(40)) for k, v in h.items()}
    return {
        "$comment": "GENERATED by extraction/build_histogram.py from the recon computed-style dumps. Top 40 values per property, usage counts across all listed files. CookieYes/UA-default text excluded.",
        "sourceFiles": sources,
        "histogram": top,
    }


if __name__ == "__main__":
    if not os.path.isdir(RECON):
        print("recon/ not present beside design-repo/: histogram not rebuilt (standalone copy)")
        sys.exit(0)
    text = json.dumps(build(), indent=1) + "\n"
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == text
        print("histogram up to date" if ok else "histogram OUT OF DATE")
        sys.exit(0 if ok else 1)
    open(OUT, "w").write(text)
    print("wrote extraction/style-histogram.json")
