#!/usr/bin/env python3
"""Generate tokens/llm/token-catalog.json: every token path, its category, type and resolved
value, plus the typography-role and motion-recipe ids. extraction/verify_all.py rebuilds it in
memory and fails on drift. Run: python3 tokens/build_catalog.py [--check]
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tokens_lib as T  # noqa: E402

OUT = os.path.join(T.TOKENS, "llm", "token-catalog.json")
VERSION = "1.0.0"

CATEGORY = {
    "foundation.color": "color", "foundation.gradient": "gradient", "foundation.font.family": "fontFamily", "foundation.font.weight": "fontWeight",
    "foundation.font.size": "fontSize", "foundation.space": "spacing", "foundation.radius": "radius", "foundation.breakpoint": "breakpoint",
    "foundation.shadow": "elevation", "foundation.blur": "blur", "foundation.duration": "motion", "foundation.easing": "motion", "foundation.delay": "motion",
    "foundation.distance": "motion", "foundation.speed": "motion", "foundation.spring": "motion", "foundation.threshold": "motion",
    "color": "semanticColor", "typography": "typography", "radius": "semanticShape", "elevation": "semanticShape",
    "container": "layout", "sectionPadding": "layout", "space": "semanticSpace", "component": "component",
}


def category(path):
    best = ""
    for p in CATEGORY:
        if (path == p or path.startswith(p + ".")) and len(p) > len(best):
            best = p
    return CATEGORY.get(best, "other")


def build():
    tree, _ = T.load_tree()
    tokens = {}
    for path, node in T.walk_tokens(tree):
        tokens[path] = {"category": category(path), "type": node.get("$type", "reference"), "value": T.resolve_value(tree, node)}
    counts = {}
    for t in tokens.values():
        counts[t["category"]] = counts.get(t["category"], 0) + 1
    typography = sorted(tree["typography"])
    recipes = sorted(tree["motion"]["recipe"])
    return {
        "version": VERSION,
        "$comment": "GENERATED by tokens/build_catalog.py. Do not hand-edit. Generators reference token paths from this list, never raw values.",
        "counts": {"tokens": len(tokens), "byCategory": dict(sorted(counts.items())), "typographyRoles": len(typography), "motionRecipes": len(recipes)},
        "typographyRoles": typography,
        "motionRecipes": recipes,
        "tokens": dict(sorted(tokens.items())),
    }


if __name__ == "__main__":
    text = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("catalog up to date" if ok else "catalog OUT OF DATE")
        sys.exit(0 if ok else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(text)
    print("wrote tokens/llm/token-catalog.json")
